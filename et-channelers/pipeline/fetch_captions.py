#!/usr/bin/env python3
"""Fetch YouTube's own caption tracks for the queued videos (no audio, no speech-to-text).

Where a video has captions, this gives a transcript in seconds instead of minutes of model time.
The files are kept apart from machine transcripts and from publisher texts, because they are a
third kind of text: written by the uploader, or generated by YouTube ("auto").

Runs yt-dlp with --skip-download and its subtitle options. No cookies, no login, no proxy, no
alternative player clients: if YouTube answers with a bot check, 403 or 429, three in a row stop
the run (exit code 3), exactly as in download_audio.py. From a cloud server YouTube refuses these
requests; run this on your own computer.

Reads   <root>/jobs/queue.csv (from select_jobs.py)
Writes  <root>/captions/<channel_dir>/<video_id>.<lang>.vtt
        <root>/captions/<channel_dir>/<video_id>.txt          plain text of the preferred track
        <root>/captions/captions_manifest.jsonl               one line per video: tracks, kind, words

    python3 pipeline/fetch_captions.py --limit 3
    python3 pipeline/fetch_captions.py --all --workers 2
"""
from __future__ import annotations

import argparse
import concurrent.futures as cf
import shutil
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import (HARD_BLOCKS, ID_RE, Breaker, Progress, RateLimiter, add_root_arg, append_jsonl,  # noqa: E402
                    atomic_write_text, classify_error, ensure_outside_git, latest_by_key, layout, normalise_text,
                    parse_shard, read_csv, read_jsonl, run_cmd, sha256_text, stable_shard, utc_now)
from fetch_publisher_text import cues_to_text  # noqa: E402

SKIP_LATER = {"unavailable", "login_required", "no_captions"}


def ytdlp_cmd(args, row, work):
    return [args.ytdlp, "--ignore-config", "--no-playlist", "--no-warnings", "--no-progress", "--skip-download",
            "--write-subs", "--write-auto-subs", "--sub-langs", args.languages, "--sub-format", "vtt",
            "--retries", "2", "--socket-timeout", "30", "--sleep-requests", "0.75", "--sleep-subtitles", "5",
            "-o", str(work / "%(id)s.%(ext)s"), row["url"]]


def fetch_one(args, row, out_root, limiter, breaker):
    video_id = row["video_id"]
    work = out_root / ".work" / video_id
    target = out_root / row["channel_dir"]
    rec = {"video_id": video_id, "channel_dir": row["channel_dir"], "started": utc_now()}
    try:
        if breaker.tripped.is_set():
            return None
        shutil.rmtree(work, ignore_errors=True)
        work.mkdir(parents=True, exist_ok=True)
        limiter.wait()
        t0 = time.time()
        code, _, err = run_cmd(ytdlp_cmd(args, row, work), args.timeout)
        rec["elapsed_s"] = round(time.time() - t0, 1)
        tracks = sorted(work.glob(f"{video_id}.*.vtt"))
        if code != 0 and not tracks:
            klass = classify_error(err)
            rec.update(status="error", error_class=klass, error_tail=(err or "").strip()[-300:])
            if klass in HARD_BLOCKS:
                breaker.hard_block()
            return rec
        breaker.success()
        if not tracks:
            rec.update(status="error", error_class="no_captions", error_tail="the video has no caption track in the requested languages")
            return rec
        target.mkdir(parents=True, exist_ok=True)
        saved = []
        for track in tracks:
            lang = track.name[len(video_id) + 1:-4]
            shutil.move(str(track), target / track.name)
            saved.append(lang)
        # prefer a track the uploader wrote ("en") over YouTube's generated one ("en-orig", "en-en" ...)
        best = sorted(saved, key=lambda lang: (len(lang), lang))[0]
        text = cues_to_text((target / f"{video_id}.{best}.vtt").read_text(encoding="utf-8", errors="replace"))
        atomic_write_text(target / f"{video_id}.txt", text + "\n")
        rec.update(status="ok", tracks=saved, preferred=best, n_words=len(text.split()),
                   text_sha256=sha256_text(normalise_text(text)), error_class="", error_tail="")
        return rec
    finally:
        shutil.rmtree(work, ignore_errors=True)
        if rec.get("status"):
            append_jsonl(out_root / "captions_manifest.jsonl", rec)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    add_root_arg(ap)
    ap.add_argument("--queue", type=Path)
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--shard")
    ap.add_argument("--workers", type=int, default=2)
    ap.add_argument("--min-interval", type=float, default=5.0, help="seconds between request starts, all workers")
    ap.add_argument("--stop-after-blocks", type=int, default=3)
    ap.add_argument("--languages", default="en.*,en", help="yt-dlp --sub-langs value")
    ap.add_argument("--timeout", type=int, default=300)
    ap.add_argument("--retry-failed", action="store_true")
    ap.add_argument("--ytdlp", default="yt-dlp")
    args = ap.parse_args()

    paths = layout(ensure_outside_git(args.root))
    out_root = paths.captions
    queue = [r for r in read_csv(args.queue or paths.jobs / "queue.csv") if ID_RE.match(r.get("video_id") or "")]
    i, n = parse_shard(args.shard)
    queue = [r for r in queue if stable_shard(r["video_id"], n) == i]
    done = latest_by_key(read_jsonl(out_root / "captions_manifest.jsonl"))
    todo = []
    for r in queue:
        prev = done.get(r["video_id"])
        if prev and prev["status"] == "ok":
            continue
        if prev and prev.get("error_class") in SKIP_LATER and not args.retry_failed:
            continue
        todo.append(r)
    print(f"queue {len(queue)} | already done or settled {len(queue) - len(todo)} | to do {len(todo)}", file=sys.stderr)
    if not args.limit and not args.all:
        print("dry run: pass --limit N for a pilot or --all for everything", file=sys.stderr)
        return
    if args.limit:
        todo = todo[:args.limit]
    if not todo:
        return
    if not shutil.which(args.ytdlp):
        sys.exit(f"{args.ytdlp} not found. Install it first (see pipeline/README.md).")
    limiter, breaker, progress = RateLimiter(args.min_interval), Breaker(args.stop_after_blocks), Progress(len(todo), "captions")
    attempted = 0
    with cf.ThreadPoolExecutor(max_workers=max(1, args.workers)) as pool:
        for rec in pool.map(lambda r: fetch_one(args, r, out_root, limiter, breaker), todo):
            if rec is not None:
                attempted += 1
                progress.tick(rec["status"] == "ok")
    print(f"attempted {attempted} of {len(todo)}; manifest {out_root / 'captions_manifest.jsonl'}", file=sys.stderr)
    if breaker.tripped.is_set():
        print("STOPPED: repeated 403 / 429 / bot-check responses. Wait, use fewer --workers or a larger "
              "--min-interval, then rerun: finished items are skipped.", file=sys.stderr)
        sys.exit(3)


if __name__ == "__main__":
    main()
